import { CreateRemediationDraftInput } from './schemas';
import { RemediationDraft } from './types';

export class DraftStore {
  private draftsById: Map<string, RemediationDraft> = new Map();
  private draftsByIdempotencyKey: Map<string, RemediationDraft> = new Map();
  private counter: number = 100;

  /**
   * Create or retrieve an existing remediation draft using idempotency key.
   * "All write operations must use an idempotency key or duplicate check."
   * "Remediation must be a local/mock ticket or pull-request draft only, clearly labelled 'draft only.'"
   */
  public createDraft(input: CreateRemediationDraftInput): RemediationDraft {
    if (this.draftsByIdempotencyKey.has(input.idempotency_key)) {
      return this.draftsByIdempotencyKey.get(input.idempotency_key)!;
    }

    this.counter += 1;
    const draftId = input.draft_type === 'github_pr'
      ? `PR-#${this.counter}`
      : `SEC-TICKET-${this.counter}`;

    const title = `[DRAFT ONLY] ${input.proposed_action} (${input.affected_identity})`;

    const bodyMarkdown = `
# ⚠️ [DRAFT ONLY] Access Debt Remediation Proposal

> **NOTICE**: This is a locally generated draft proposal. **NO PERMISSIONS HAVE BEEN MUTATED.**
> Approval from a designated system owner is required prior to applying any change.

---

### Finding Summary
- **Affected Identity**: \`${input.affected_identity}\`
- **Target Resource**: \`${input.affected_resource}\`
- **Candidate Edge for Removal**: \`${input.candidate_edge_id}\`
- **Proposed Action**: ${input.proposed_action}

### Rationale & Graph Evidence
${input.rationale}

### Minimum-Change Rationale
Aks simulated this change against the active access graph. Removing this single relationship closes the indirect access path to the high-sensitivity resource while preserving all legitimate peer access routes.

### Rollback & Restore Instructions
In the event of unexpected service disruption, execute the following restore step:
\`\`\`bash
# Rollback Hint:
${input.rollback_hint}
\`\`\`

---
*Generated by Aks (Explainable Graph-Grounded Access Debt Agent)*
*Draft ID: ${draftId} | Idempotency Key: ${input.idempotency_key}*
`.trim();

    const draft: RemediationDraft = {
      draft_id: draftId,
      idempotency_key: input.idempotency_key,
      status: 'DRAFT_ONLY',
      draft_type: input.draft_type,
      created_at: new Date().toISOString(),
      title,
      body_markdown: bodyMarkdown,
      affected_identity: input.affected_identity,
      affected_resource: input.affected_resource,
      candidate_edge_id: input.candidate_edge_id,
      proposed_action: input.proposed_action,
      rollback_instructions: input.rollback_hint,
      disclaimer: 'DRAFT ONLY - Requires human security approver. No live systems mutated.',
    };

    this.draftsById.set(draftId, draft);
    this.draftsByIdempotencyKey.set(input.idempotency_key, draft);

    return draft;
  }

  public getDraft(draftId: string): RemediationDraft | undefined {
    return this.draftsById.get(draftId);
  }

  public getAllDrafts(): RemediationDraft[] {
    return Array.from(this.draftsById.values());
  }

  public updateDraftStatus(
    draftId: string,
    status: RemediationDraft['status']
  ): RemediationDraft | undefined {
    const draft = this.draftsById.get(draftId);
    if (!draft) return undefined;
    draft.status = status;
    return draft;
  }
}

